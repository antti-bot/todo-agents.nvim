local plugin = vim.fn.getcwd()
vim.opt.rtp:prepend(plugin)
vim.cmd('runtime plugin/todo_agents.lua')
local task = require('todo_agents.task')
local agent = require('todo_agents')
local fake = { 'python3', plugin .. '/tests/fake_codex.py' }
local function eq(a, b) assert(vim.deep_equal(a, b), vim.inspect(a) .. ' != ' .. vim.inspect(b)) end
local function line(text)
  vim.cmd('enew!')
  vim.api.nvim_buf_set_lines(0, 0, -1, false, { text, 'Context: keep this unsaved text.' })
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
end
local function record(id)
  return vim.json.decode(table.concat(vim.fn.readfile(vim.fn.stdpath('state') .. '/todo-agents/' .. id .. '.json'), '\n'))
end
local function test()
  local project = vim.fn.stdpath('state') .. '/project with spaces'
  vim.fn.mkdir(project, 'p')
  local function git(args, cwd)
    local argv = { 'git', '-C', cwd or project }
    vim.list_extend(argv, args)
    local result = vim.system(argv, { text = true }):wait()
    assert(result.code == 0, result.stderr)
    return vim.trim(result.stdout)
  end
  git({ 'init', '-b', 'main' })
  git({ 'config', 'user.name', 'Plugin Test' })
  git({ 'config', 'user.email', 'test@example.invalid' })
  vim.fn.writefile({ 'initial' }, project .. '/tracked.txt')
  git({ 'add', '.' }); git({ 'commit', '-m', 'Initial' })
  vim.cmd.cd(vim.fn.fnameescape(project))
  local launches = {}
  local termopen = vim.fn.termopen
  vim.fn.termopen = function(argv, opts)
    launches[#launches + 1] = vim.deepcopy(argv)
    return termopen(argv, opts)
  end
  for _, text in ipairs({ '- [ ] task', '  * [x] task', '+ [X] task', '12. [ ] task', '2) [ ] task' }) do assert(task.parse(text)) end
  eq(task.parse('plain text'), nil)
  eq(task.parse('- [a] task'), nil)
  eq(task.link(task.parse('- [ ] Fix [login]'), 'abc'), '- [ ] [Fix \\[login\\]](codex://abc)')
  line('- [ ] task')
  agent.setup({ mappings = false, command = fake })
  agent.open(true)
  local terminal = vim.api.nvim_get_current_buf()
  local id = vim.b.todo_agent_id
  assert(vim.wait(3000, function() return record(id).session_id ~= nil end, 20))
  local meta = record(id)
  assert(meta.session_id ~= id and #meta.session_id == 36)
  assert(vim.uv.fs_stat(meta.worktree))
  eq(meta.cwd, meta.worktree)
  eq(git({ 'branch', '--show-current' }, meta.worktree), meta.branch)
  eq(pcall(agent.cleanup), false)
  eq(launches[1], { fake[1], fake[2], meta.prompt })
  local snapshot = vim.fn.stdpath('state') .. '/todo-agents/' .. id .. '.md'
  eq(vim.fn.readfile(snapshot)[2], 'Context: keep this unsaved text.')
  vim.cmd('wincmd p')
  local todo = vim.api.nvim_get_current_buf()
  eq(task.parse(vim.api.nvim_get_current_line()).id, meta.session_id)
  vim.api.nvim_buf_set_text(todo, 0, 3, 0, 4, { 'x' })
  assert(vim.api.nvim_get_current_line():match('^%- %[x%]'))
  agent.open(); eq(vim.api.nvim_get_current_buf(), terminal)
  vim.fn.jobstop(vim.b.terminal_job_id)
  assert(vim.wait(3000, function() return not vim.uv.fs_stat(meta.worktree) end, 20))
  git({ 'show-ref', '--verify', 'refs/heads/' .. meta.branch })
  vim.api.nvim_set_current_buf(todo)
  agent.open(); assert(vim.b.terminal_job_id)
  eq(launches[2], { fake[1], fake[2], 'resume', meta.session_id })
  assert(vim.uv.fs_stat(meta.worktree))
  eq(pcall(agent.bind, 'another-session'), false)
  eq(record(id).session_id, meta.session_id)
  vim.fn.jobstop(vim.b.terminal_job_id)
  assert(vim.wait(3000, function() return not vim.uv.fs_stat(meta.worktree) end, 20))
  line('- [ ] Bind manually')
  agent.setup({ mappings = false, command = { fake[1], fake[2], '--no-transcript' } })
  agent.open()
  local manual = vim.b.todo_agent_id
  agent.bind('manual-session-id')
  eq(record(manual).session_id, 'manual-session-id')
  vim.fn.jobstop(vim.b.terminal_job_id)
  assert(vim.wait(3000, function() return not vim.uv.fs_stat(record(manual).worktree) end, 20))
  line('- [ ] untouched')
  agent.setup({ command = { '/does/not/exist' } })
  eq(pcall(agent.open), false)
  eq(vim.api.nvim_get_current_line(), '- [ ] untouched')
  line('- [x] completed')
  eq(pcall(agent.open), false)
  local wt = require('todo_agents.worktree')
  local item = { id = 'worktree-test', cwd = project }
  local state = vim.fn.stdpath('state') .. '/worktree-fixture'
  wt.prepare(item, state)
  local parallel = { id = 'parallel-task', cwd = project }
  wt.prepare(parallel, state)
  assert(parallel.worktree ~= item.worktree and parallel.branch ~= item.branch)
  eq(wt.cleanup(parallel), true)
  local original = git({ 'rev-parse', 'HEAD' }, project)
  vim.fn.writefile({ 'agent change' }, item.worktree .. '/tracked.txt')
  eq(wt.cleanup(item), false)
  eq(vim.fn.readfile(project .. '/tracked.txt')[1], 'initial')
  git({ 'add', '.' }, item.worktree)
  git({ 'commit', '-m', 'Agent work' }, item.worktree)
  local committed = git({ 'rev-parse', 'HEAD' }, item.worktree)
  assert(committed ~= original)
  eq(wt.cleanup(item), true)
  assert(not vim.uv.fs_stat(item.worktree))
  wt.prepare(item, state)
  eq(git({ 'rev-parse', 'HEAD' }, item.worktree), committed)
  vim.fn.writefile({ 'untracked' }, item.worktree .. '/scratch.txt')
  eq(wt.cleanup(item), false)
  vim.fn.delete(item.worktree .. '/scratch.txt')
  vim.fn.writefile({ 'secret' }, item.worktree .. '/.gitignore')
  git({ 'add', '.' }, item.worktree)
  git({ 'commit', '-m', 'Ignore secrets' }, item.worktree)
  vim.fn.writefile({ 'keep me' }, item.worktree .. '/secret')
  eq(wt.cleanup(item), false)
  vim.fn.delete(item.worktree .. '/secret')
  git({ 'checkout', '--detach' }, item.worktree)
  eq(wt.cleanup(item), false)
  git({ 'checkout', item.branch }, item.worktree)
  eq(wt.cleanup(item), true)
  eq(git({ 'rev-parse', 'HEAD' }, project), original)
  line('- [ ] failed launch')
  agent.setup({ command = fake })
  local before = git({ 'worktree', 'list', '--porcelain' })
  vim.fn.termopen = function() error('simulated process launch failure') end
  eq(pcall(agent.open), false)
  eq(vim.api.nvim_get_current_line(), '- [ ] failed launch')
  eq(git({ 'worktree', 'list', '--porcelain' }), before)
  vim.fn.termopen = termopen
  local outside = vim.fn.stdpath('state') .. '/outside-git'
  vim.fn.mkdir(outside, 'p'); vim.cmd.cd(outside)
  line('- [ ] no git repository')
  eq(pcall(agent.open), false)
  eq(vim.api.nvim_get_current_line(), '- [ ] no git repository')
  print('Task and worktree tests passed')
end
local ok, err = xpcall(test, debug.traceback)
if not ok then io.stderr:write(err .. '\n'); vim.cmd('cquit 1') else vim.cmd('qa!') end
