dofile('tests/home.lua')
local plugin = vim.fn.getcwd()
vim.opt.rtp:prepend(plugin)
local agent = require('todo_agents')
local repos = require('todo_agents.worktree')
local function eq(a, b) assert(vim.deep_equal(a, b), vim.inspect(a) .. ' != ' .. vim.inspect(b)) end
local function git(root, args)
  local argv = { 'git', '-C', root }
  vim.list_extend(argv, args)
  local result = vim.system(argv, { text = true }):wait()
  assert(result.code == 0, result.stderr)
  return vim.trim(result.stdout)
end
local function record(id)
  return vim.json.decode(table.concat(vim.fn.readfile(vim.fn.stdpath('state') .. '/todo-agents/' .. id .. '.json'), '\n'))
end
local function key(lhs)
  local map = vim.fn.maparg(lhs, 'n', false, true)
  assert(type(map.callback) == 'function', 'Missing callback: ' .. lhs)
  map.callback()
end
local function test()
  local root = vim.fn.stdpath('state') .. '/repo folders'
  local paths = { root .. '/api', root .. '/web' }
  for _, path in ipairs(paths) do
    vim.fn.mkdir(path, 'p')
    git(path, { 'init', '-b', 'main' })
    git(path, { 'config', 'user.name', 'Plugin Test' })
    git(path, { 'config', 'user.email', 'test@example.invalid' })
    vim.fn.writefile({ 'initial' }, path .. '/file.txt')
    git(path, { 'add', '.' }); git(path, { 'commit', '-m', 'Initial' })
  end
  local content = { '# Plan', './api/', '- [ ] API task', '', './web/', '- [ ] Web task',
    '', './api/', './web/', '- [ ] Still only web', '', '```', './missing/', '- [ ] Code example', '```', '- [ ] Web again' }
  local file = root .. '/plan.md'
  vim.fn.writefile(content, file)
  local fake = { 'python3', plugin .. '/tests/fake_codex.py' }
  local notifications, other_links = 0, 0
  vim.notify = function() notifications = notifications + 1 end
  vim.keymap.set('n', 'gx', function() other_links = other_links + 1 end, { desc = 'User gx' })
  agent.setup({ command = fake })
  vim.cmd.cd(vim.fn.fnameescape(root))
  vim.cmd.edit(vim.fn.fnameescape(file))
  local plan = vim.api.nvim_get_current_buf()
  eq(vim.fn.maparg('gx', 'n', false, true).buffer, 1)
  eq(vim.fn.maparg('<CR>', 'n'), '')
  eq(vim.fn.maparg('<C-v>', 'n'), '')
  eq(repos.validate(repos.selected(plan, 3)), paths[1])
  eq(repos.validate(repos.selected(plan, 6)), paths[2])
  eq(repos.validate(repos.selected(plan, 10)), paths[2])
  eq(repos.validate(repos.selected(plan, 16)), paths[2])
  eq(pcall(repos.selected, plan, 14), false)
  eq(repos.absolute('~/code/api', root), vim.fn.expand('~') .. '/code/api')
  eq(git(paths[1], { 'worktree', 'list', '--porcelain' }):find('todo-agent', 1, true), nil)
  eq(git(paths[2], { 'worktree', 'list', '--porcelain' }):find('todo-agent', 1, true), nil)
  local launches, termopen = {}, vim.fn.termopen
  vim.fn.termopen = function(argv, opts)
    launches[#launches + 1] = { argv = vim.deepcopy(argv), cwd = opts.cwd }
    return termopen(argv, opts)
  end
  local echo = vim.api.nvim_echo
  local errors = 0
  vim.api.nvim_echo = function() errors = errors + 1 end
  for _, heading in ipairs({ './missing/', '# Missing folder', root }) do
    vim.api.nvim_buf_set_lines(plan, 0, -1, false, { paths[1], heading, '- [ ] Ignore this' })
    vim.api.nvim_win_set_cursor(0, { 3, 0 })
    key('gx')
    eq(vim.api.nvim_get_current_buf(), plan)
    eq(vim.api.nvim_get_current_line(), '- [ ] Ignore this')
    eq(#launches, 0)
  end
  eq(errors, 0)
  vim.api.nvim_echo = echo
  vim.api.nvim_buf_set_lines(plan, 0, -1, false, content)
  vim.api.nvim_win_set_cursor(0, { 3, 0 })
  local windows = #vim.api.nvim_list_wins()
  key('gx')
  local terminal, id = vim.api.nvim_get_current_buf(), vim.b.todo_agent_id
  eq(#vim.api.nvim_list_wins(), windows)
  vim.cmd('buffer #')
  eq(vim.api.nvim_get_current_buf(), plan)
  eq(vim.api.nvim_win_get_cursor(0)[1], 3)
  key('gx')
  eq(vim.api.nvim_get_current_buf(), terminal)
  eq(#launches, 1)
  assert(vim.wait(3000, function() return record(id).session_id ~= nil end, 20))
  local meta = record(id)
  eq(meta.repo, paths[1])
  eq(launches[1].cwd, meta.worktree)
  eq(launches[1].argv, fake)
  eq(vim.fn.readfile(file), content)
  vim.cmd('buffer #')
  local linked = vim.api.nvim_get_current_line()
  assert(linked:find('(codex://' .. meta.session_id .. ')', 1, true))
  eq(record(meta.session_id).id, id)
  vim.fn.writefile({ meta.session_id, id }, vim.env.XDG_STATE_HOME .. '/reopen-session')
  vim.api.nvim_buf_set_text(plan, 2, 3, 2, 4, { 'x' })
  assert(vim.api.nvim_get_current_line():match('^%- %[x%]'))
  vim.api.nvim_win_set_cursor(0, { 3, 10 })
  key('gx')
  eq(vim.api.nvim_get_current_buf(), terminal)
  eq(other_links, 0)
  vim.fn.writefile({ 'changed' }, meta.worktree .. '/file.txt')
  vim.fn.jobstop(vim.b.terminal_job_id)
  vim.wait(200, function() return false end)
  assert(vim.uv.fs_stat(meta.worktree))
  eq(notifications, 0)
  vim.cmd('buffer #')
  agent.open()
  eq(#vim.api.nvim_list_wins(), windows)
  eq(launches[2].argv, { fake[1], fake[2], 'resume', meta.session_id })
  eq(vim.fn.readfile(meta.worktree .. '/file.txt'), { 'changed' })
  git(meta.worktree, { 'restore', 'file.txt' })
  vim.fn.jobstop(vim.b.terminal_job_id)
  assert(vim.wait(3000, function() return not vim.uv.fs_stat(meta.worktree) end, 20))
  vim.cmd('buffer #')
  vim.cmd('enew!')
  local notes = vim.api.nvim_get_current_buf()
  eq(vim.fn.maparg('gx', 'n', false, true).buffer, 0)
  vim.api.nvim_buf_set_lines(notes, 0, -1, false, { '[Earlier session](codex://' .. meta.session_id .. ')', 'https://example.com' })
  vim.api.nvim_exec_autocmds('TextChanged', { buffer = notes })
  eq(vim.fn.maparg('gx', 'n', false, true).buffer, 1)
  vim.api.nvim_win_set_cursor(0, { 2, 3 }); key('gx'); eq(other_links, 1)
  vim.api.nvim_win_set_cursor(0, { 1, 4 }); key('gx')
  eq(launches[3].argv, { fake[1], fake[2], 'resume', meta.session_id })
  assert(vim.uv.fs_stat(meta.worktree))
  vim.fn.jobstop(vim.b.terminal_job_id)
  assert(vim.wait(3000, function() return not vim.uv.fs_stat(meta.worktree) end, 20))
  vim.cmd('buffer #')
  eq(vim.api.nvim_get_current_buf(), notes)
  vim.cmd('enew!')
  vim.api.nvim_buf_set_lines(0, 0, -1, false, { paths[2], '- [ ] Web task' })
  vim.api.nvim_exec_autocmds('TextChanged', { buffer = vim.api.nvim_get_current_buf() })
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  key('gx')
  local web = record(vim.b.todo_agent_id)
  eq(web.repo, paths[2])
  assert(not vim.uv.fs_stat(meta.worktree))
  vim.fn.jobstop(vim.b.terminal_job_id)
  assert(vim.wait(3000, function() return not vim.uv.fs_stat(web.worktree) end, 20))
  vim.cmd('buffer #')
  vim.cmd('enew!')
  vim.api.nvim_buf_set_lines(0, 0, -1, false, { paths[1], '- [ ] Finish' })
  local finish = vim.api.nvim_get_current_buf()
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  agent.setup({ command = { fake[1], fake[2], '--exit=0' } })
  agent.open()
  local finished = record(vim.b.todo_agent_id)
  assert(vim.wait(3000, function() return not vim.uv.fs_stat(finished.worktree) end, 20))
  vim.cmd('buffer #')
  eq(vim.api.nvim_get_current_buf(), finish)
  eq(vim.api.nvim_win_get_cursor(0)[1], 2)
  eq(notifications, 0)
  vim.fn.termopen = termopen
  print('Repo scope and session link tests passed')
end
local ok, err = xpcall(test, debug.traceback)
if not ok then io.stderr:write(err .. '\n'); vim.cmd('cquit 1') else vim.cmd('qa!') end
